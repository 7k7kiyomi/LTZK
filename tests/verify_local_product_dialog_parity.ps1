$ErrorActionPreference = 'Stop'

$root = Split-Path -Parent $PSScriptRoot
$adapterSource = Get-Content -Raw -Encoding UTF8 (Join-Path $root 'LocalProductOperation.cpp')
$project = Get-Content -Raw -Encoding UTF8 (Join-Path $root 'LTZK.vcxproj')

function Assert-Contains([string]$text, [string]$token, [string]$message) {
    if (-not $text.Contains($token)) { throw $message }
}

function Assert-FileContains([string]$path, [string]$token, [string]$message) {
    if (-not (Test-Path -LiteralPath $path)) {
        throw "Missing expected platform dialog UI file: $path"
    }
    $text = Get-Content -Raw -Encoding UTF8 $path
    Assert-Contains $text $token $message
}

$rangeUiPath = Join-Path $root 'LocalRangeExport.ui'
$mainAreaUiPath = Join-Path $root 'LocalMainAreaClip.ui'

# The platform dialogs must carry the same control contract as the database dialogs.
Assert-FileContains $rangeUiPath 'radioButton_manualDraw' `
    'The local range dialog must expose the manual-draw mode.'
Assert-FileContains $rangeUiPath 'comboBox_layer' `
    'The local range dialog must expose the vector-layer selector.'
Assert-FileContains $rangeUiPath 'comboBox_format' `
    'The local range dialog must expose the database dialog format selector.'
Assert-FileContains $mainAreaUiPath 'comboBox_encoding' `
    'The local main-area dialog must expose the encoding selector.'
Assert-FileContains $mainAreaUiPath 'checkBox_overwrite' `
    'The local main-area dialog must expose overwrite behavior.'
Assert-FileContains $mainAreaUiPath 'groupBox_cartography' `
    'The local main-area dialog must expose the cartography controls.'
Assert-FileContains $mainAreaUiPath 'groupBox_scale' `
    'The local main-area dialog must expose scale and inner-frame controls.'

Assert-Contains $project '<QtUic Include="LocalRangeExport.ui" />' `
    'The platform range dialog UI must be generated by the host project.'
Assert-Contains $project '<QtUic Include="LocalMainAreaClip.ui" />' `
    'The platform main-area dialog UI must be generated by the host project.'
Assert-Contains $adapterSource '#include "ui_LocalRangeExport.h"' `
    'The local range operation must use the parity UI.'
Assert-Contains $adapterSource '#include "ui_LocalMainAreaClip.h"' `
    'The local main-area operation must use the parity UI.'
Assert-Contains $adapterSource 'LocalRangeExportDialog' `
    'The local range operation must use a full parity dialog implementation.'
Assert-Contains $adapterSource 'LocalMainAreaClipDialog' `
    'The local main-area operation must use a full parity dialog implementation.'
Assert-Contains $adapterSource 'checkBox_overwrite' `
    'The local export path must read the same overwrite control as the database dialog.'
Assert-Contains $adapterSource 'comboBox_encoding' `
    'The local export path must read the same encoding control as the database dialog.'

$pluginChanges = rg -n 'localSources|LocalProductOperation|localProductsFromRequest' `
    (Join-Path $root 'map_product_manager_tools') `
    --glob '!**/GeneratedFiles/**' --glob '!**/node_modules/**' 2>$null
if ($LASTEXITCODE -eq 0 -and $pluginChanges) {
    throw "Product-manager plugin source must remain unchanged:`n$pluginChanges"
}

Write-Output 'Local product dialog parity verification passed.'
